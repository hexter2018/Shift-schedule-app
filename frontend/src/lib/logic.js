export function hexToRgb(hex){
  const h = hex.replace("#","");
  return [parseInt(h.slice(0,2),16), parseInt(h.slice(2,4),16), parseInt(h.slice(4,6),16)];
}
export function tint(hex, amount){
  const [r,g,b] = hexToRgb(hex);
  const mix = (c)=> Math.round(c + (255-c)*amount);
  return `rgb(${mix(r)},${mix(g)},${mix(b)})`;
}
export function tintHex(hex, amount){
  const [r,g,b] = hexToRgb(hex);
  const mix = (c)=> Math.round(c + (255-c)*amount);
  const toHex = (n)=> n.toString(16).padStart(2,"0").toUpperCase();
  return toHex(mix(r))+toHex(mix(g))+toHex(mix(b));
}
export function hexNoHash(hex){ return (hex||"000000").replace("#","").toUpperCase(); }

export function daysInMonth(yearBE, month1to12){
  const yearCE = yearBE - 543;
  return new Date(yearCE, month1to12, 0).getDate();
}
export function weekdayLabel(yearBE, month1to12, day){
  const yearCE = yearBE - 543;
  return THAI_WEEKDAYS[new Date(yearCE, month1to12-1, day).getDay()];
}
export function isWeekend(yearBE, month1to12, day){
  const yearCE = yearBE - 543;
  const wd = new Date(yearCE, month1to12-1, day).getDay();
  return wd === 0 || wd === 6;
}
export function weekdayIndexOf(yearBE, month1to12, day){
  const yearCE = yearBE - 543;
  return new Date(yearCE, month1to12-1, day).getDay(); // 0=Sun ... 6=Sat
}
export function globalDayIndex(yearBE, month1to12, day){
  const yearCE = yearBE - 543;
  return Math.round(Date.UTC(yearCE, month1to12-1, day) / 86400000);
}
export function nextMonthOf(month, yearBE){
  return month === 12 ? {month:1, yearBE: yearBE+1} : {month: month+1, yearBE};
}
export function prevMonthOf(month, yearBE){
  return month === 1 ? {month:12, yearBE: yearBE-1} : {month: month-1, yearBE};
}

export function parseCellValue(raw){
  if(!raw) return {base:"", wh:false, th:false, ot:false};
  const v = raw.trim().toUpperCase();
  if(v.endsWith("WH") && v.length>2){
    return {base:v.slice(0,-2), wh:true, th:false, ot:false};
  }
  if(v.endsWith("TH") && v.length>2){
    return {base:v.slice(0,-2), wh:false, th:true, ot:false};
  }
  if(v.endsWith("OT") && v.length>2){
    return {base:v.slice(0,-2), wh:false, th:false, ot:true};
  }
  return {base:v, wh:false, th:false, ot:false};
}

export function styleForCell(raw, shiftCodes){
  const {base, wh, th, ot} = parseCellValue(raw);
  const def = shiftCodes.find(c=>c.code.toUpperCase()===base);
  if(!def){
    if(base==="WH") return {bg:"#efece4", fg:"#6b645c", border:"none"};
    if(!base) return {bg:"transparent", fg:"var(--ink)", border:"none"};
    return {bg:"#f3f1ec", fg:"#8a8378", border:"none"};
  }
  const bg = tint(def.color, (wh||th) ? 0.55 : 0.86);
  let border = "none";
  if(wh) border = `2px dashed ${def.color}`;
  if(th) border = `2px dotted #b91c1c`;
  if(ot) border = `2px solid #db2777`;
  return {bg, fg:def.color, border};
}

/* ---------- shortcut-key expansion ----------
   Mirrors the VBA "Select Case inputValue" lookup: type a short code in a
   day cell, tab/click away (or press Enter), and it expands to the full
   shift code. Typing the full code directly still works as before. */
export const SHORTCUT_MAP = {
  // --- M series ---
  "6":"M6",  "6W":"M6WH",  "6T":"M6TH",  "6O":"M6OT",
  "8":"M8",  "8W":"M8WH",  "8T":"M8TH",  "8O":"M8OT",
  "MM":"MM6","MT":"MM6TH", "MO":"MM6OT",
  // --- E series ---
  "2":"E2",  "2W":"E2WH",  "2T":"E2TH",  "2O":"E2OT",
  "EE":"EE6","ET":"EE6TH", "EO":"EE6OT",
  // --- N series ---
  "10":"N10","10W":"N10WH","10T":"N10TH","10O":"N10OT",
  // --- leave ---
  "L":"LA"
};
export function expandShortcut(val){
  if(!val) return val;
  const key = val.trim().toUpperCase();
  return Object.prototype.hasOwnProperty.call(SHORTCUT_MAP, key) ? SHORTCUT_MAP[key] : key;
}

/* ---------- pattern detection ---------- */
export function isPatternWildcard(v){
  if(!v) return true;
  if(v === "LA") return true;
  if(v.endsWith("TH")) return true;
  if(v.endsWith("OT") && v.length>2) return true;
  return false;
}

export function wildcardFallbackBase(v){
  if(!v || !v.endsWith("TH") || v.length<=2) return null;
  const base = v.slice(0, -2);
  if(!base || base === "WH") return null;
  return base;
}

export function detectCycle(daysArray){
  const n = daysArray.length;
  const nonBlank = daysArray.filter(v=>!isPatternWildcard(v));
  if(nonBlank.length < Math.max(3, Math.floor(n*0.4))) return null; // not enough data

  const maxTrustedL = Math.max(1, Math.floor(n/2));
  for(let L=1; L<=Math.min(MAX_CYCLE, maxTrustedL); L++){
    const phases = new Array(L).fill(null);
    let ok = true;
    for(let i=0; i<n && ok; i++){
      const v = daysArray[i];
      if(isPatternWildcard(v)) continue;
      const p = i % L;
      if(phases[p] === null){
        phases[p] = v;
      } else if(phases[p] !== v){
        ok = false;
      }
    }
    if(ok && phases.some(p=>p!==null)){
      for(let p=0; p<L; p++){
        if(phases[p] !== null) continue;
        for(let i=p; i<n; i+=L){
          const fb = wildcardFallbackBase(daysArray[i]);
          if(fb){ phases[p] = fb; break; }
        }
      }
      const cycle = phases.map(p=>p===null? "" : p);
      return {length:L, cycle, confidence:"high"};
    }
  }
  const cycle = daysArray.map(v=> (isPatternWildcard(v) ? (wildcardFallbackBase(v) || "") : v));
  return {length:n, cycle, confidence:"low"};
}

export function phaseValue(pattern, yearBE, month, day){
  const anchorDay = pattern.anchorDay || 1;
  const idx = globalDayIndex(yearBE, month, day) - globalDayIndex(pattern.anchorYearBE, pattern.anchorMonth, anchorDay);
  const L = pattern.length;
  const phase = ((idx % L) + L) % L;
  return pattern.cycle[phase] || "";
}

/* ---------- leave (LA) & mandatory-OT coverage suggestion ---------- */
export function isOvernightCode(codeBase, shiftCodes){
  const def = shiftCodes.find(c=>c.code.toUpperCase()===codeBase);
  if(!def || !def.start || !def.end) return false;
  return def.start > def.end; // e.g. "22:00" > "07:00" crosses midnight
}

export function computeOtCounts(state){
  const counts = {};
  const nd = daysInMonth(state.yearBE, state.month);
  state.employees.forEach(emp=>{
    const key = patternKeyFor(emp) || emp.id;
    let c = 0;
    for(let d=1; d<=nd; d++){
      const {ot} = parseCellValue(emp.days[d]);
      if(ot) c++;
    }
    counts[key] = c;
  });
  return counts;
}

export function vacatedShiftFor(emp, day, state, patternLib){
  const key = patternKeyFor(emp);
  const pattern = key ? patternLib[key] : null;
  if(pattern) return phaseValue(pattern, state.yearBE, state.month, day);
  return "";
}

export function findOtCandidates(leaveEmp, day, vacatedBase, groupFilter, state){
  const otCounts = computeOtCounts(state);
  const list = state.employees
    .filter(e=>(!leaveEmp || e.id!==leaveEmp.id) && !e.excludeFromOt)
    .filter(e=>!groupFilter || (e.shiftGroup||"").trim()===groupFilter)
    .map(e=>{
      const todayRaw = (e.days[day]||"").trim().toUpperCase();
      const {base:todayBase, wh:todayWh} = parseCellValue(todayRaw);
      const prevRaw = day>1 ? (e.days[day-1]||"").trim().toUpperCase() : "";
      const {base:prevBase} = parseCellValue(prevRaw);
      const prevOvernight = !!(prevBase && isOvernightCode(prevBase, state.shiftCodes));
      const alreadySameShift = todayBase === vacatedBase && !todayWh;
      const onLeaveToday = todayBase === "LA";
      const key = patternKeyFor(e) || e.id;
      return { emp:e, todayBase, todayWh, prevOvernight, alreadySameShift, onLeaveToday, otCount: otCounts[key] || 0 };
    })
    .filter(c => !c.onLeaveToday && !c.alreadySameShift);

  list.sort((a,b)=>{
    const aOff = (a.todayWh || !a.todayBase) ? 0 : 1;
    const bOff = (b.todayWh || !b.todayBase) ? 0 : 1;
    if(aOff !== bOff) return aOff - bOff;
    if(a.prevOvernight !== b.prevOvernight) return (a.prevOvernight?1:0) - (b.prevOvernight?1:0);
    return a.otCount - b.otCount;
  });
  return list.slice(0,5);
}

