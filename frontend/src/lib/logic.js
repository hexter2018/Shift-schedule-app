export function addCompensatoryWH(emp, fromDay, nd, state, holidays){
  for(let d=fromDay+1; d<=nd; d++){
    const raw = (emp.days[d]||"").trim().toUpperCase();
    const {base, wh, th, ot} = parseCellValue(raw);
    if(wh || th || ot || base==="LA") continue;
    if(isHoliday(state.yearBE, state.month, d, holidays)) continue;
    emp.days[d] = base ? (base+"WH") : "WH";
    emp.autoFlags[d] = true;
    return d;
  }
  return null;
}

export function applyHolidayOverridesForMonth(state, holidays){
  const nd = daysInMonth(state.yearBE, state.month);
  let converted = 0, compensated = 0, unplaced = 0;
  for(let d=1; d<=nd; d++){
    const hol = isHoliday(state.yearBE, state.month, d, holidays);
    if(!hol) continue;
    state.employees.forEach(emp=>{
      if(!emp.autoFlags) emp.autoFlags = {};
      const raw = (emp.days[d]||"").trim().toUpperCase();
      if(!raw) return;
      const {base, wh, th, ot} = parseCellValue(raw);
      if(!base || base==="LA" || th || ot) return;
      const newVal = base + "TH";
      if(raw !== newVal){
        emp.days[d] = newVal;
        emp.autoFlags[d] = true;
        converted++;
      }
      if(wh){
        const placedAt = addCompensatoryWH(emp, d, nd, state, holidays);
        if(placedAt) compensated++; else unplaced++;
      }
    });
  }
  return {converted, compensated, unplaced};
}

/* ---------- rotating weekly off-day pair per shift group ---------- */
export function rotationPairForGroup(groupKey, groupRotations, state){
  const cfg = groupRotations[groupKey];
  if(!cfg) return null;
  const monthsSince = (state.yearBE*12 + state.month) - (cfg.anchorYearBE*12 + cfg.anchorMonth);
  const step = cfg.stepDays || 2;
  let start = (cfg.anchorStartDay + step*monthsSince) % 7;
  if(start < 0) start += 7;
  return [start, (start+1) % 7];
}

export function applyGroupRotationsForMonth(state, groupRotations, holidays){
  const nd = daysInMonth(state.yearBE, state.month);
  let placed = 0, reverted = 0, skippedHoliday = 0;
  const groupsApplied = [];
  Object.keys(groupRotations).forEach(groupKey=>{
    const cfg = groupRotations[groupKey];
    const pair = rotationPairForGroup(groupKey, groupRotations, state);
    if(!pair) return;
    groupsApplied.push({group:groupKey, pair});
    const memberKeys = cfg.memberKeys || [];
    const members = state.employees.filter(e=>{
      const k = patternKeyFor(e);
      return k && memberKeys.includes(k);
    });
    members.forEach(emp=>{
      if(!emp.autoFlags) emp.autoFlags = {};
      if(!emp.rotationFlags) emp.rotationFlags = {};
      for(let d=1; d<=nd; d++){
        const wd = weekdayIndexOf(state.yearBE, state.month, d);
        const inPair = pair.includes(wd);
        const raw = (emp.days[d]||"").trim().toUpperCase();
        const {base, wh, th, ot} = parseCellValue(raw);
        if(inPair){
          if(isHoliday(state.yearBE, state.month, d, holidays)){ skippedHoliday++; continue; }
          if(th || ot || base==="LA") continue;
          const newVal = base ? (base+"WH") : "WH";
          if(raw !== newVal){
            emp.days[d] = newVal;
            emp.autoFlags[d] = true;
            emp.rotationFlags[d] = true;
            placed++;
          }
        } else if(wh && emp.rotationFlags[d]){
          emp.days[d] = base || "";
          delete emp.autoFlags[d];
          delete emp.rotationFlags[d];
          reverted++;
        }
      }
    });
  });
  return {placed, reverted, skippedHoliday, groupsApplied};
}

/* ---------- fill 3-shift rotation gaps (MM6 / EE6) ---------- */
export function fixThreeShiftGaps(state){
  const nd = daysInMonth(state.yearBE, state.month);
  const ORDER = ["M6","E2","N10"];
  const groups = {};
  state.employees.forEach(emp=>{
    const g = (emp.shiftGroup||"").trim();
    if(!g) return;
    (groups[g] = groups[g]||[]).push(emp);
  });

  let converted = 0, otWarnings = 0;
  const log = [];

  Object.keys(groups).forEach(groupName=>{
    const members = groups[groupName];
    for(let d=1; d<=nd; d++){
      const todayInfo = members.map(emp=>{
        const raw = (emp.days[d]||"").trim().toUpperCase();
        const {base, wh, th, ot} = parseCellValue(raw);
        return {emp, base, working: !!(base && !wh && !th && !ot && base!=="LA")};
      });
      const present = new Set(todayInfo.filter(t=>t.working).map(t=>t.base));
      const missing = ORDER.filter(code=>!present.has(code));
      if(missing.length !== 1) continue;
      const missingCode = missing[0];
      const dateLabel = `วันที่ ${d} (${weekdayLabel(state.yearBE, state.month, d)})`;

      if(missingCode === "N10"){
        otWarnings++;
        const candidates = findOtCandidates(null, d, "N10", groupName, state);
        log.push({type:"ot-warning", group:groupName, dateLabel, day:d, candidates});
        continue;
      }

      const [earlyCode, lateCode] = ORDER.filter(code=>code!==missingCode);
      const earlyWorker = todayInfo.find(t=>t.working && t.base===earlyCode);
      const lateWorker = todayInfo.find(t=>t.working && t.base===lateCode);
      const did = [];
      if(earlyWorker){
        earlyWorker.emp.days[d] = "MM6";
        if(!earlyWorker.emp.autoFlags) earlyWorker.emp.autoFlags = {};
        earlyWorker.emp.autoFlags[d] = true;
        converted++;
        did.push(`${earlyWorker.emp.name||earlyWorker.emp.empCode}: ${earlyCode}→MM6`);
      }
      if(lateWorker){
        lateWorker.emp.days[d] = "EE6";
        if(!lateWorker.emp.autoFlags) lateWorker.emp.autoFlags = {};
        lateWorker.emp.autoFlags[d] = true;
        converted++;
        did.push(`${lateWorker.emp.name||lateWorker.emp.empCode}: ${lateCode}→EE6`);
      }
      log.push({
        type:"converted", group:groupName, dateLabel, missingCode,
        result: did.length ? did.join(", ") : "ไม่พบคนทำกะที่จะปรับให้ (ไม่มีใครทำงานในกะที่เหลือวันนั้น)"
      });
    }
  });
  return {converted, otWarnings, groupCount: Object.keys(groups).length, log};
}
